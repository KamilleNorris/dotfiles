#!/usr/bin/env bash
# Feeds require-agent-comment-prefix.sh hook payloads and checks the decision.
set -euo pipefail

hook="$(cd "$(dirname "$0")" && pwd)/require-agent-comment-prefix.sh"
passed=0
failed=0

body_for() {
    local first="$1" agent="$2"
    printf '%s\n\n[%s]\n' "$first" "Generated by ${agent}"
}

# Prints a shell command whose heredoc is the comment body.
gh_with_body() {
    local invocation="$1" body="$2"
    printf '%s\n%s\n%s\n' \
        "${invocation} \"\$(cat <<'END'" \
        "$body" \
        "END"
    printf '%s\n' ')"'
}

payload() {
    local agent="$1" tool="$2" command="${3:-}" body="${4:-}"
    jq -n \
        --arg agent "$agent" \
        --arg tool "$tool" \
        --arg command "$command" \
        --arg body "$body" \
        '{
            hook_event_name: (if $agent == "claude" then "PreToolUse" else "preToolUse" end),
            tool_name: $tool,
            tool_input: (
                if $tool == "Shell" then {command: $command}
                else {commentBody: $body}
                end
            )
        }
        + (if $agent == "cursor" then {cursor_version: "1.7.2"} else {} end)'
}

check() {
    local name="$1" input="$2" want_status="$3" want_decision="$4" want_reason="${5:-}"
    local out err status decision reason
    err="$(mktemp)"
    set +e
    out="$(printf '%s' "$input" | "$hook" 2>"$err")"
    status=$?
    set -e
    if [[ "$status" -eq 2 ]]; then
        decision="deny"
        reason="$(cat "$err")"
    elif [[ -z "$out" ]]; then
        decision="allow"
        reason=""
    else
        decision="$(jq -r '.permission // .hookSpecificOutput.permissionDecision // "unknown"' <<<"$out")"
        reason="$(jq -r '.user_message // .hookSpecificOutput.permissionDecisionReason // empty' <<<"$out")"
    fi
    rm -f "$err"

    local problem=""
    [[ "$status" -eq "$want_status" ]] || problem+="status ${status}, want ${want_status}; "
    [[ "$decision" == "$want_decision" ]] || problem+="decision ${decision}, want ${want_decision}; "
    if [[ -n "$want_reason" && "$reason" != *"$want_reason"* ]]; then
        problem+="reason missing '${want_reason}': ${reason}; "
    fi
    if [[ -n "$problem" ]]; then
        printf 'FAIL %s\n  %s\n' "$name" "$problem"
        failed=$((failed + 1))
    else
        printf 'ok   %s\n' "$name"
        passed=$((passed + 1))
    fi
}

cursor_gh() {
    local name="$1" command="$2" status="$3" decision="$4" reason="${5:-}"
    check "$name" "$(payload cursor Shell "$command")" "$status" "$decision" "$reason"
}

# Label shapes, through the GitHub heredoc path.
cursor_gh "bold label, colon inside" \
    "$(gh_with_body "gh api --method POST repos/o/r/pulls/1/comments -f body=" "$(body_for '**suggestion:** short summary' Cursor)")" \
    0 allow
cursor_gh "bold label, colon outside" \
    "$(gh_with_body "gh api --method POST repos/o/r/pulls/1/comments -f body=" "$(body_for '**suggestion**: short summary' Cursor)")" \
    0 allow
cursor_gh "bold label with decoration" \
    "$(gh_with_body "gh api --method POST repos/o/r/pulls/1/comments -f body=" "$(body_for '**issue (blocking):** pin can be overwritten' Cursor)")" \
    0 allow
cursor_gh "plain label still allowed" \
    "$(gh_with_body "gh pr comment 1 --body=" "$(body_for 'suggestion: short summary' Cursor)")" \
    0 allow
cursor_gh "unbalanced bold" \
    "$(gh_with_body "gh api --method POST repos/o/r/pulls/1/comments -f body=" "$(body_for '**suggestion: short summary' Cursor)")" \
    0 deny "conventional comment"
cursor_gh "unknown label" \
    "$(gh_with_body "gh api --method POST repos/o/r/pulls/1/comments -f body=" "$(body_for '**not-a-label:** short summary' Cursor)")" \
    0 deny "conventional comment"
cursor_gh "agent line must match the caller" \
    "$(gh_with_body "gh api --method POST repos/o/r/pulls/1/comments -f body=" "$(body_for '**suggestion:** short summary' Claude)")" \
    0 deny "[Generated by Cursor]"
cursor_gh "agent line must be the last line" \
    "$(gh_with_body "gh api --method POST repos/o/r/pulls/1/comments -f body=" "$(printf '%s\nthanks\n' "$(body_for '**suggestion:** short summary' Cursor)")")" \
    0 deny "[Generated by Cursor]"
cursor_gh "leading blank lines are ignored" \
    "$(gh_with_body "gh pr review 1 --body=" "$(printf '\n\n%s' "$(body_for '**question:** which pin' Cursor)")")" \
    0 allow

# Commands that are not a comment post stay allowed.
cursor_gh "unrelated command" "git status" 0 allow
cursor_gh "reading comments is allowed" "gh api --method GET repos/o/r/pulls/1/comments" 0 allow
cursor_gh "review without a body" "gh pr review 1 --approve" 0 allow
cursor_gh "body file is rejected" \
    "gh api --method POST repos/o/r/pulls/1/comments --input /tmp/body.md" \
    0 deny "heredoc"

# Same event name as Kiro; cursor_version selects the Cursor line.
check "cursor_version wins over the shared event name" \
    "$(payload cursor Shell "$(gh_with_body "gh pr comment 1 --body=" "$(body_for '**suggestion:** short summary' Kiro)")")" \
    0 deny "[Generated by Cursor]"

check "kiro accepts its own line" \
    "$(payload kiro addOrEditJiraIssueComment "" "$(body_for '**suggestion:** short summary' Kiro)")" \
    0 allow
check "kiro deny exits 2" \
    "$(payload kiro addOrEditJiraIssueComment "" "missing both")" \
    2 deny "conventional comment"
check "claude accepts its own line" \
    "$(payload claude addCommentToJiraIssue "" "$(body_for '**praise:** the guard is clear' Claude)")" \
    0 allow
check "claude deny is a permission decision" \
    "$(payload claude addCommentToJiraIssue "" "missing both")" \
    0 deny "conventional comment"

printf '%s passed, %s failed\n' "$passed" "$failed"
[[ "$failed" -eq 0 ]]
